const STORAGE_PURCHASES_KEY = 'vorcarozap:commercial-purchases';
const STORAGE_FOLLOWED_VITRINES_KEY = 'vorcarozap:followed-vitrines';

export function loadCommercialPurchases() {
  try {
    const raw = localStorage.getItem(STORAGE_PURCHASES_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveCommercialPurchase(productId) {
  try {
    const list = loadCommercialPurchases();
    if (!list.includes(productId)) {
      list.push(productId);
      localStorage.setItem(STORAGE_PURCHASES_KEY, JSON.stringify(list));
    }
  } catch {
    // Ignore storage issues
  }
}

export function loadFollowedVitrines() {
  try {
    const raw = localStorage.getItem(STORAGE_FOLLOWED_VITRINES_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return new Set(Array.isArray(parsed) ? parsed : []);
  } catch {
    return new Set();
  }
}

export function saveFollowedVitrines(idsSet) {
  try {
    localStorage.setItem(STORAGE_FOLLOWED_VITRINES_KEY, JSON.stringify([...idsSet]));
  } catch {
    // Ignore storage issues
  }
}

